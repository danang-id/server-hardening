func umaskControl() *defaultUmask {
	return &defaultUmask{control.Base{M: control.Meta{ID: umaskID}}}
}

const stockDefs = "MAIL_DIR\t/var/mail\nUMASK\t\t022\nHOME_MODE\t0700\n"

// What authselect generates in /etc/pam.d/postlogin.
const stockPostlogin = "# Generated by authselect\nsession     optional      pam_umask.so silent\nsession     optional      pam_lastlog.so silent noupdate showfailed\n"

func umaskEnv(t *testing.T) *control.Env {
	env, _ := testEnv(t)
	writeFile(t, env, loginDefs, stockDefs)
	writeFile(t, env, "/etc/pam.d/postlogin", stockPostlogin)
	return env
}

func TestUmaskApplyAndRevert(t *testing.T) {
	ctx := context.Background()
	env := umaskEnv(t)
	c := umaskControl()
	if state(t, c, env) != control.NotApplied {
		t.Fatal("should start not applied")
	}
	must(t, c.Apply(ctx, env, control.Values{"umask": {"027"}}))
	defs := read(t, env, loginDefs)
	wantContains(t, defs, "UMASK\t\t027", "MAIL_DIR\t/var/mail", "HOME_MODE\t0700")
	if strings.Contains(defs, "022") || strings.Count(defs, "UMASK") != 1 {
		t.Fatalf("login.defs: %s", defs)
	}
	wantContains(t, read(t, env, umaskProfile), managed(umaskID), "umask 027")
	if read(t, env, "/etc/pam.d/postlogin") != stockPostlogin {
		t.Fatal("the PAM files are generated by authselect and must not be edited")
	}
	if state(t, c, env) != control.Applied {
		t.Fatal("should be applied")
	}

	writeFile(t, env, loginDefs, stockDefs)
	if state(t, c, env) != control.Partial {
		t.Fatal("a changed login.defs is partial")
	}

	must(t, c.Revert(ctx, env))
	if read(t, env, loginDefs) != stockDefs {
		t.Fatal("login.defs must come back as it was")
	}
	noFile(t, env, umaskProfile)
	if env.Rec.Has(umaskID) {
		t.Fatal("record should be gone")
	}
}

func TestUmaskAddsTheLineWhenLoginDefsHasNone(t *testing.T) {
	env := umaskEnv(t)
	writeFile(t, env, loginDefs, "MAIL_DIR\t/var/mail\n")
	must(t, umaskControl().Apply(context.Background(), env, control.Values{"umask": {"0077"}}))
	wantContains(t, read(t, env, loginDefs), "UMASK\t\t077")
	wantContains(t, read(t, env, umaskProfile), "umask 077")
}

// The first port read the Debian file /etc/pam.d/common-session, which AlmaLinux
// does not have, and failed on a real server.
func TestUmaskWorksWithoutDebianPAMFiles(t *testing.T) {
	env := umaskEnv(t)
	must(t, umaskControl().Apply(context.Background(), env, control.Values{"umask": {"027"}}))
	noFile(t, env, "/etc/pam.d/common-session")
}

func TestUmaskWarnsWhenNoPAMSessionRunsPamUmask(t *testing.T) {
	env := umaskEnv(t)
	writeFile(t, env, "/etc/pam.d/postlogin", "session optional pam_lastlog.so silent\n")
	var warned []string
	env.Log = &memLog{warns: &warned}
	must(t, umaskControl().Apply(context.Background(), env, control.Values{"umask": {"027"}}))
	if !strings.Contains(strings.Join(warned, "\n"), "pam_umask") {
		t.Fatalf("the person must be told about pam_umask: %v", warned)
	}
	var quiet []string
	env2 := umaskEnv(t)
	env2.Log = &memLog{warns: &quiet}
	must(t, umaskControl().Apply(context.Background(), env2, control.Values{"umask": {"027"}}))
	if len(quiet) != 0 {
		t.Fatalf("no warning when pam_umask is there: %v", quiet)
	}
}

func TestUmaskRejectsBadValues(t *testing.T) {
	env := umaskEnv(t)
	for _, v := range []string{"22", "028", "000", "0o27", "027\nUMASK 000", "xyz", "020"} {
		if err := umaskControl().Apply(context.Background(), env, control.Values{"umask": {v}}); err == nil {
			t.Fatalf("%q must be refused", v)
		}
	}
	if read(t, env, loginDefs) != stockDefs {
		t.Fatal("nothing may change after a refusal")
	}
}

func TestUmaskNeedsLoginDefs(t *testing.T) {
	env := umaskEnv(t)
	noFileAt(t, env, loginDefs)
	if err := umaskControl().Apply(context.Background(), env, control.Values{"umask": {"027"}}); err == nil {
		t.Fatal("expected an error")
	}
	noFile(t, env, umaskProfile)
}
